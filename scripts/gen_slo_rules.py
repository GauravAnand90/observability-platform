#!/usr/bin/env python3
"""Generate prometheus/rules/slo-recording.yml from the SLO definitions below.

Adding an SLO = adding one entry to SLOS. The burn-rate alerts, the error-budget
rule and the Grafana dashboards are generic over {service, slo}, so they pick it
up with no other changes. Requires PyYAML (pip install pyyaml).
"""
import pathlib
import yaml

OUT = pathlib.Path(__file__).resolve().parent.parent / "prometheus" / "rules"
SVC = 'service="checkout-api",route="/api/checkout"'
SLOS = [
    dict(name="checkout-availability", objective=0.999, budget=0.001,
         desc="99.9% of checkout requests succeed (non-5xx) over 30 days",
         err='sum(rate(http_requests_total{%s,code=~"5.."}[{w}]))\n/\nsum(rate(http_requests_total{%s}[{w}]))' % (SVC, SVC)),
    dict(name="checkout-latency", objective=0.99, budget=0.01,
         desc="99% of checkout requests complete within 300ms over 30 days",
         err='1 - (\n  sum(rate(http_request_duration_seconds_bucket{%s,le="0.3"}[{w}]))\n  /\n  sum(rate(http_request_duration_seconds_count{%s}[{w}]))\n)' % (SVC, SVC)),
]
WINDOWS = ["5m", "30m", "1h", "2h", "6h", "1d", "3d"]

class Lit(str):
    """Rendered as a YAML block scalar so PromQL stays readable."""


class Dumper(yaml.SafeDumper):
    def ignore_aliases(self, data):  # no &id001 anchors in the output
        return True


Dumper.add_representer(Lit, lambda d, v: d.represent_scalar("tag:yaml.org,2002:str", v, style="|"))

groups = []
for s in SLOS:
    labels = {"service": "checkout-api", "slo": s["name"]}
    rules = [
        # Constants live in the 1m group: alerts read them, and a slower group
        # could leave gaps inside Prometheus's 5m lookback window.
        {"record": "slo:objective:ratio", "expr": f"vector({s['objective']})", "labels": labels},
        {"record": "slo:error_budget:ratio", "expr": f"vector({s['budget']})", "labels": labels},
    ] + [{"record": f"slo:sli_error:ratio_rate{w}", "expr": Lit(s["err"].replace("{w}", w) + "\n"), "labels": labels} for w in WINDOWS]
    groups.append({"name": f"slo-{s['name']}-sli", "interval": "1m", "rules": rules})
    # The 30-day ratio only feeds dashboards and the budget-remaining rule; it is
    # expensive, so it runs less often (still well inside the 5m lookback).
    groups.append({"name": f"slo-{s['name']}-30d", "interval": "2m", "rules": [
        {"record": "slo:sli_error:ratio_rate30d", "expr": Lit(s["err"].replace("{w}", "30d") + "\n"), "labels": labels},
    ]})
groups.append({"name": "slo-error-budget", "interval": "2m", "rules": [
    {"record": "slo:error_budget_remaining:ratio",
     "expr": Lit("1 - (\n  slo:sli_error:ratio_rate30d\n  / on(service, slo)\n  slo:error_budget:ratio\n)\n")},
]})

header = """# GENERATED by scripts/gen_slo_rules.py. Edit the SLO definitions there, then run `make rules`.
#
# SLI error ratios recorded per SLO over every window the burn-rate alerts use.
# Naming follows level:metric:operations; every series carries {service, slo}
# so the alerts and dashboards in this repo work unchanged for any new SLO.
#
""" + "\n".join(f"#   {s['name']}: {s['desc']}" for s in SLOS) + "\n\n"
(OUT / "slo-recording.yml").write_text(header + yaml.dump({"groups": groups}, Dumper=Dumper, sort_keys=False, width=200))
print(f"wrote {OUT / 'slo-recording.yml'}")
